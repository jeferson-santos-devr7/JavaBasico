public class Exercicio18 {
    public static void main(String[] args) {
        int maior = Math.max(45, 78);
        int menor = Math.min(45, 78);
        int absoluto = Math.abs(-12);

        System.out.println("Maior entre 45 e 78: " + maior);
        System.out.println("Menor entre 45 e 78: " + menor);
        System.out.println("Valor absoluto de -12: " + absoluto);
    }
}